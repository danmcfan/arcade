def text(s, color, scale=1, spacing=1):
    s = s.upper()
    w = len(s) * (5 + spacing) - spacing
    im = Image.new("RGBA", (max(w, 1), 7), (0, 0, 0, 0))
    px = im.load()
    for i, ch in enumerate(s):
        bits = G.get(ch, G[" "]).ljust(35, ".")
        for j, b in enumerate(bits[:35]):
            if b == "#":
                px[i * (5 + spacing) + j % 5, j // 5] = color + (255,)
    if scale > 1:
        im = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
    return im


def shadowed(s, color, shadow, scale=1):
    """Text with a 1-pixel drop shadow (in font pixels)."""
    t = text(s, color, 1)
    sh = text(s, shadow, 1)
    im = Image.new("RGBA", (t.width + 1, t.height + 1), (0, 0, 0, 0))
    im.alpha_composite(sh, (1, 1))
    im.alpha_composite(t, (0, 0))
    if scale > 1:
        im = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
    return im
