def build(head, body, dy=0):
    rows = [r for r in BODIES[body].strip("\n").split("\n") if r.strip()]
    tall = len(rows) > 6
    c = Image.new("RGBA", (16, 16), CLEAR)
    b = grid(BODIES[body], P, max(len(r) for r in rows), len(rows))
    c.alpha_composite(b, (0, 0 if tall else 9))
    c.alpha_composite(grid(HEADS[head], P, 16, 9), (0, 0))
    if dy:
        moved = Image.new("RGBA", (16, 16), CLEAR)
        moved.alpha_composite(c.crop((0, max(0, -dy), 16, 16 - max(0, dy))), (0, max(0, dy)))
        c = moved
    return outline(c, INK)


def climb_top(stage):
    """Hauling up over a ledge: only the upper body shows above the girder."""
    full = build("back", "climb1" if stage == 1 else "climb2")
    c = Image.new("RGBA", (16, 16), CLEAR)
    cut = 9 if stage == 1 else 12
    c.alpha_composite(full.crop((0, 0, 16, cut)), (0, 16 - cut))
    return c


def _flat():
    """Lying on his back, X eyes, antenna bulb dark."""
    d = build("dead", "stand").rotate(90)
    c = Image.new("RGBA", (16, 16), CLEAR)
    d = d.crop(d.getbbox())
    c.alpha_composite(d, ((16 - d.width) // 2, 16 - d.height))
    return c


def frames():
    f = {}
    f["stand"] = build("right", "stand")
    f["run_1"] = build("right", "run1")
    f["run_2"] = build("right", "run2", dy=-1)
    f["run_3"] = build("right", "run3")
    f["run_4"] = build("right", "run4", dy=-1)
    f["jump"] = build("right", "jump", dy=-1)
    f["climb_1"] = build("back", "climb1")
    f["climb_2"] = build("back", "climb2")
    f["climb_top_1"] = climb_top(1)
    f["climb_top_2"] = climb_top(2)
    f["land"] = build("right", "land", dy=1)
    f["victory"] = build("happy", "victory")
    f["wrench_up_1"] = build("right", "wrench_up1")
    f["wrench_up_2"] = build("right", "wrench_up2", dy=-1)
    f["wrench_down_1"] = build("right", "wrench_down1")
    f["wrench_down_2"] = build("right", "wrench_down2", dy=-1)
    f["blink"] = build("blink", "stand")
    f["hurt"] = build("zap", "stand")
    f["dead_zap_1"] = build("zap", "stand")
    f["dead_zap_2"] = build("dead", "stand")
    f["dead_spin_1"] = f["dead_zap_2"].rotate(-90)
    f["dead_spin_2"] = f["dead_zap_2"].rotate(180)
    f["dead_spin_3"] = f["dead_zap_2"].rotate(90)
    f["dead"] = _flat()
    return f


