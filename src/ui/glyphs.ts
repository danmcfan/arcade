/** Sheet order: glyph `i` sits at column `i % sheetColumns`, row `i / sheetColumns`. */
export const charset: readonly string[] = Object.keys(glyphs);

/**
 * Ink colours, one band of the sheet each (Sweetie 16, the palette the
 * rest of the game's art uses).
 */
export const inks = {
  white: "#f4f4f4",
  yellow: "#ffcd75",
  orange: "#ef7d57",
  blue: "#94b0c2",
  grey: "#566c86",
  dark: "#1a1c2c",
} as const;
export type Ink = keyof typeof inks;
export const inkOrder: readonly Ink[] = Object.keys(inks) as Ink[];

/** Rows of glyphs per ink band. */
export const bandRows = Math.ceil(charset.length / sheetColumns);
export const fontSheetWidth = sheetColumns * cell;
export const fontSheetHeight = bandRows * cell * inkOrder.length;

