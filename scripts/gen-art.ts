// Write every PNG the art sources declare, and the image table the game imports:
//
//   bun run art   # writes each declared PNG, and src/engine/images.generated.ts
//
// Each source declares its outputs once (scripts/image-outputs.ts). `artSources`
// runs them in order; no source reads another's output, so a source that ever
// does must come after it here. The table holds every output under
// src/assets/images: one group per folder (`images` for the top level,
// `<folder>Images` below it), each image keyed by its camelCase file name.
// gen-art.test.ts fails when a committed PNG or the table drifts.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { PNG } from "pngjs";
import { format, resolveConfig } from "prettier";
import { repoRoot } from "./repo-root.ts";
import { brassMonkeyArtFiles } from "./gen-brass-monkey-art.ts";
import { cabinetFiles } from "./gen-cabinets.ts";
import { fireflyArtFiles } from "./gen-firefly-art.ts";
import { sweetSamArtFiles } from "./gen-sweet-sam-art.ts";
import { uiArtFiles } from "./gen-ui-art.ts";
import type { ImageOutput } from "./image-outputs.ts";

/** Every art source's outputs, in the order `bun run art` writes them. */
export const artSources: readonly (readonly [source: string, outputs: readonly ImageOutput[]])[] = [
  ["scripts/gen-ui-art.ts", uiArtFiles],
  ["scripts/gen-cabinets.ts", cabinetFiles],
  ["scripts/gen-firefly-art.ts", fireflyArtFiles],
  ["scripts/gen-brass-monkey-art.ts", brassMonkeyArtFiles],
  ["scripts/gen-sweet-sam-art.ts", sweetSamArtFiles],
];

export const allOutputs: readonly ImageOutput[] = artSources.flatMap(([, outputs]) => outputs);

/** The image table the game imports, written by `bun run art`. */
export const tablePath = join(repoRoot, "src/engine/images.generated.ts");

const tableDir = "src/assets/images/";

function camel(kebab: string): string {
  return kebab.replaceAll(/[-/]([a-z0-9])/gu, (_m, c: string) => c.toUpperCase());
}

interface TableEntry {
  readonly group: string;
  readonly key: string;
  readonly ident: string;
  readonly output: ImageOutput;
}

/** The outputs under src/assets/images, each with its group, key and URL import; throws on a clash. */
export function tableEntries(outputs: readonly ImageOutput[]): TableEntry[] {
  const seen = new Set<string>();
  return outputs
    .filter((o) => o.file.startsWith(tableDir))
    .map((output) => {
      const rel = output.file.slice(tableDir.length).replace(/\.png$/u, "");
      const folder = posix.dirname(rel);
      const group = folder === "." ? "images" : `${camel(folder)}Images`;
      const key = camel(posix.basename(rel));
      if (!/^[a-z][A-Za-z0-9]*$/u.test(key)) throw new Error(`${output.file}: ${key} is not a camelCase name`);
      if (seen.has(`${group}.${key}`)) throw new Error(`${output.file}: ${group}.${key} is declared twice`);
      seen.add(`${group}.${key}`);
      return { group, key, ident: `${camel(rel)}Url`, output };
    });
}

/** src/engine/images.generated.ts for `outputs`, formatted as Prettier would. */
export async function imageTable(outputs: readonly ImageOutput[] = allOutputs): Promise<string> {
  const entries = tableEntries(outputs);
  const groups = [...new Set(entries.map((e) => e.group))];
  const lines = [
    "// Generated by `bun run art` (scripts/gen-art.ts) from the image outputs each art source declares.",
    "// Do not edit: declare or change an image in its source and run `bun run art`.",
    "",
    'import { imageAsset } from "./image.ts";',
    "",
    ...entries.map((e) => `import ${e.ident} from "../${e.output.file.slice("src/".length)}";`),
  ];
  for (const g of groups) {
    lines.push("", `export const ${g} = {`);
    for (const e of entries.filter((x) => x.group === g))
      lines.push(`  ${e.key}: imageAsset(${e.ident}, ${e.output.width}, ${e.output.height}),`);
    lines.push("} as const;");
  }
  return format(lines.join("\n"), { ...(await resolveConfig(tablePath)), filepath: tablePath });
}

if (import.meta.main) {
  for (const [source, outputs] of artSources) {
    for (const { file, render } of outputs) {
      const png = render();
      const path = join(repoRoot, file);
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, PNG.sync.write(png));
      console.log(`wrote ${file} (${png.width}x${png.height}) from ${source}`);
    }
  }
  writeFileSync(tablePath, await imageTable());
  console.log(`wrote ${tablePath}`);
}
